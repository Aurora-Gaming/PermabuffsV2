namespace Permabuffs_V2
{
	/// <summary>
	/// "无计时器 buff"（宠物 / 坐骑 / 光环）判定。
	///
	/// 这类 buff 本身不会倒计时，给了也不会掉，没必要也不应该写进数据库常驻。
	/// 用 HashSet 取代原来的 List.Contains，把每次 O(n) 线性扫描降到 O(1)——
	/// 原版在每个心跳里对每个玩家逐个判断，1 秒一次 × 全服玩家 × 140 个 ID。
	///
	/// 注意：原版把 348(Strategist)、353(Shimmering)、370、374、377、384 同时
	/// 写进了本表和 Config 的 probuffs/debuffs 分组，导致这些 buff 在
	/// probuffs 组里"只会瞬发一次、根本不会常驻"，是配置与代码互相矛盾的历史遗留。
	/// 这里保留原表以兼容既有行为，但额外提供 extraNoTimerBuffs 供管理员按需扩展。
	/// </summary>
	public static class BuffIDs
	{
		private static readonly HashSet<int> BuffsWithNoTimer = new()
		{
			19, 27, 40, 41, 42, 45, 49, 50, 51, 52, 53, 54, 55, 56, 57,
			61, 64, 65, 66, 81, 82, 84, 85, 90, 91, 92, 101, 102, 127, 128, 129, 130, 131, 132, 136, 141, 142, 143, 152, 154, 155,
			162, 168, 190, 191, 193, 200, 201, 202, 212, 214, 217, 218, 219, 230, 258, 259, 260, 261, 262, 263, 264, 265, 266, 267,
			268, 274, 275, 276, 277, 278, 279, 280, 281, 282, 283, 284, 285, 286, 287, 288, 289, 290, 291, 292, 293, 294, 295, 296,
			297, 298, 299, 300, 301, 302, 303, 304, 305, 317, 318, 327, 328, 329, 330, 331, 338, 341, 342, 345, 346, 348, 349, 351,
			352, 353, 354, 356, 366, 370, 371, 372, 373, 374, 377, 378, 379, 380, 381, 382, 384, 387, 388
		};

		/// <summary>该 buff 是否没有倒计时（宠物/坐骑类）。true = 不会自然消失，不入库存。</summary>
		public static bool BuffHasTimer(this int buffID) => !BuffsWithNoTimer.Contains(buffID);
	}
}
